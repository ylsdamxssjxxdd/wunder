struct ThreadRegistry {
    // A bounded active writer retains its gate, preventing two open handles
    // for the same root from accidentally creating independent thread locks.
    gates: Mutex<HashMap<String, Weak<AsyncMutex<()>>>>,
    writers: Mutex<HashMap<String, Arc<ActiveThreadWriter>>>,
    admissions: OnceLock<Semaphore>,
    queued_bytes: OnceLock<Arc<Semaphore>>,
    _root_owner: Arc<File>,
}

struct ActiveThreadWriter {
    recorder: RolloutRecorder,
    _owner: File,
    _gate: Arc<AsyncMutex<()>>,
}

fn shared_registry(root: &Path) -> Result<Arc<ThreadRegistry>> {
    static REGISTRIES: OnceLock<Mutex<HashMap<PathBuf, Weak<ThreadRegistry>>>> = OnceLock::new();
    let mut roots = REGISTRIES.get_or_init(Mutex::default).lock();
    roots.retain(|_, registry| registry.strong_count() > 0);
    if let Some(registry) = roots.get(root).and_then(Weak::upgrade) {
        return Ok(registry);
    }
    let owner = OpenOptions::new()
        .create(true)
        .truncate(false)
        .read(true)
        .write(true)
        .open(root.join(".canonical-store.lock"))?;
    owner.try_lock().map_err(|_|anyhow!("canonical storage root already belongs to another process; each server node requires its own root and thread routing"))?;
    let registry = Arc::new(ThreadRegistry {
        gates: Mutex::default(),
        writers: Mutex::default(),
        admissions: OnceLock::new(),
        queued_bytes: OnceLock::new(),
        _root_owner: Arc::new(owner),
    });
    roots.insert(root.to_owned(), Arc::downgrade(&registry));
    Ok(registry)
}

