const MAX_CONTEXT_SCAN_RECORDS: usize = 65_536;
const STRESS_BATCH_MAX_RECORDS: usize = 128;
// Leave room for the RolloutRecord timestamp/ordinal envelope generated by
// append_canonical and for a full single record before flushing a batch.
const STRESS_BATCH_MAX_BYTES: usize = ROLLOUT_MAX_APPEND_BYTES / 2;
const STRESS_ENVELOPE_BYTES: usize = 128;

struct StressRecordBatch {
    records: Vec<CanonicalRecord>,
    bytes: usize,
}

struct StressRecordSize(usize);

impl std::io::Write for StressRecordSize {
    fn write(&mut self, bytes: &[u8]) -> std::io::Result<usize> {
        self.0 = self
            .0
            .checked_add(bytes.len())
            .filter(|size| *size <= ROLLOUT_MAX_RECORD_BYTES)
            .ok_or_else(|| {
                std::io::Error::new(
                    std::io::ErrorKind::InvalidInput,
                    "stress record exceeds size limit",
                )
            })?;
        Ok(bytes.len())
    }

    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}

impl StressRecordBatch {
    fn new() -> Self {
        Self {
            records: Vec::with_capacity(STRESS_BATCH_MAX_RECORDS),
            bytes: 0,
        }
    }

    fn take(&mut self) -> Vec<CanonicalRecord> {
        self.bytes = 0;
        std::mem::replace(
            &mut self.records,
            Vec::with_capacity(STRESS_BATCH_MAX_RECORDS),
        )
    }

    fn needs_flush_before(&self, bytes: usize) -> bool {
        !self.records.is_empty()
            && (self.records.len() >= STRESS_BATCH_MAX_RECORDS
                || self.bytes.saturating_add(bytes) > STRESS_BATCH_MAX_BYTES)
    }

    fn push(&mut self, record: CanonicalRecord, bytes: usize) {
        self.records.push(record);
        self.bytes = self.bytes.saturating_add(bytes);
    }

    fn full(&self) -> bool {
        self.records.len() >= STRESS_BATCH_MAX_RECORDS || self.bytes >= STRESS_BATCH_MAX_BYTES
    }
}

