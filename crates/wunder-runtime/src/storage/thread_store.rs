const MAX_ACTIVE_THREADS: usize = 128;
const MAX_CONTEXT_RECORDS: u32 = 8192;
const MAX_CONTEXT_BYTES: u32 = 16 * 1024 * 1024;
const CONTEXT_READ_BLOCK_BYTES: usize = 64 * 1024;
