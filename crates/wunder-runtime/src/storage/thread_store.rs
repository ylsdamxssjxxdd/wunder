    /// Startup-only schema initialization; performs no history scan or replay.
    /// Call this constructor on the application's initialization worker.
    pub fn open(root: impl AsRef<Path>) -> Result<Self> {
        let root = root.as_ref().to_path_buf();
        std::fs::create_dir_all(&root).context("create storage root")?;
        let root = root.canonicalize().context("resolve storage root")?;
        let registry = shared_registry(&root)?;
        let state_path = root.join("state_1.sqlite");
        let conn = connect(&state_path)?;
        conn.execute_batch("PRAGMA journal_mode=WAL;")?;
        conn.execute_batch(
            "CREATE TABLE IF NOT EXISTS canonical_threads (
                thread_id TEXT PRIMARY KEY NOT NULL,
                rollout_id TEXT UNIQUE NOT NULL,
                rollout_path TEXT NOT NULL,
                status TEXT NOT NULL,
                created_at_ms INTEGER NOT NULL,
                updated_at_ms INTEGER NOT NULL,
                title TEXT,
                workspace_id TEXT,
                pinned INTEGER NOT NULL DEFAULT 0
             );
             CREATE INDEX IF NOT EXISTS canonical_threads_directory
                ON canonical_threads(updated_at_ms DESC,thread_id DESC);
             CREATE INDEX IF NOT EXISTS canonical_threads_status ON canonical_threads(status,thread_id);
             CREATE TABLE IF NOT EXISTS canonical_rollouts (
                rollout_id TEXT PRIMARY KEY NOT NULL,
                owner_thread_id TEXT NOT NULL,
                rollout_path TEXT UNIQUE NOT NULL,
                created_at_ms INTEGER NOT NULL,
                start_ordinal INTEGER NOT NULL,
                base_rollout_id TEXT REFERENCES canonical_rollouts(rollout_id),
                base_end_ordinal INTEGER,
                base_end_byte_offset INTEGER,
                CHECK ((base_rollout_id IS NULL AND base_end_ordinal IS NULL AND base_end_byte_offset IS NULL)
                    OR (base_rollout_id IS NOT NULL AND base_end_ordinal IS NOT NULL AND base_end_byte_offset IS NOT NULL))
             );
             CREATE INDEX IF NOT EXISTS canonical_rollouts_reference ON canonical_rollouts(base_rollout_id);",
        )?;
        Ok(Self {
            state_path: Arc::new(state_path),
            history: ThreadHistoryStore::open(root.join("thread_history_1.sqlite"))?,
            admissions_store: super::thread_admission::TurnAdmissions::open(&root)?,
            registry,
            root: Arc::new(root),
            compression_enabled: false,
            history_verified: Arc::default(),
        })
    }

