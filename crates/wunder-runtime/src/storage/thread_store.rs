    /// One explicitly requested cold pass. Indexed keyset pages, a strict
    /// file limit, and one compression worker keep maintenance bounded. The
    /// default configuration performs no work and creates no pass marker.
    pub async fn compress_cold_rollouts(&self, limit: u32) -> ThreadStoreResult<CompressionReport> {
        if limit == 0 || limit > 1024 {
            return Err(ThreadStoreError::Conflict {
                message: "compression limit must be between 1 and 1024".into(),
            });
        }
        if !self.compression_enabled {
            return Ok(CompressionReport::default());
        }
        let root = self.root.clone();
        let Some(mut pass) = blocking::run_fs("thread_store.compression_pass", move || {
            MaintenancePass::begin(&root)
        })
        .await
        .map_err(unavailable)?
        else {
            return Ok(CompressionReport {
                cooldown: true,
                ..Default::default()
            });
        };
        let mut report = CompressionReport::default();
        let mut after = String::new();
        let started = std::time::Instant::now();
        while report.examined < limit && started.elapsed() < Duration::from_secs(5 * 60 * 60) {
            let state_path = self.state_path.clone();
            let cursor = after.clone();
            let count = (limit - report.examined).min(64);
            let ids = db(move || {
                let conn = connect(&state_path)?;
                let mut query = conn.prepare("SELECT thread_id FROM canonical_threads WHERE thread_id>?1 ORDER BY thread_id LIMIT ?2")?;
                let rows = query.query_map(params![cursor, count], |row| row.get::<_,String>(0))?;
                Ok(rows.collect::<rusqlite::Result<Vec<_>>>()?)
            }).await?;
            if ids.is_empty() {
                break;
            }
            for id in ids {
                after = id.clone();
                report.examined += 1;
                let thread = ThreadId::new(id)?;
                let gate = self.gate(&thread)?;
                let Ok(_gate) = gate.try_lock() else {
                    continue;
                };
                if self.registry.writers.lock().contains_key(thread.as_str()) {
                    continue;
                }
                let Ok(_owner) = self.owner_lock(&thread).await else {
                    continue;
                };
                let stored = self.stored(&thread).await?;
                let segments = self.lineage_segments(&stored.metadata.thread_id).await?;
                let compressed = blocking::run_fs("thread_store.compress_cold", move || {
                    let mut compressed = 0;
                    for segment in segments {
                        if rollout_compression::compress_rollout(
                            segment.path,
                            &CompressionOptions {
                                enabled: true,
                                ..Default::default()
                            },
                        )?
                        .is_some()
                        {
                            compressed += 1;
                        }
                    }
                    Ok(compressed)
                })
                .await
                .map_err(unavailable)?;
                report.compressed += compressed;
            }
        }
        blocking::run_fs("thread_store.compression_complete", move || pass.complete())
            .await
            .map_err(unavailable)?;
        Ok(report)
    }

