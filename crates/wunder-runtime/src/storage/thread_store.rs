fn read_model_context_lineage(
    segments: &[LineageSegment],
    request: ModelContextRequest,
) -> Result<ModelContext> {
    let mut records = Vec::with_capacity((request.max_records as usize).min(128));
    let mut used = 0usize;
    let mut latest_ordinal = None;
    let mut previous_ordinal = None;
    let mut truncated = false;
    let mut scanned_records = 0usize;
    let mut scanned_bytes = 0u64;
    'segments: for (segment_index, segment) in segments.iter().enumerate().rev() {
        let mut lines = ReverseContextLines::open(&segment.path, segment.end.as_ref())?;
        let mut first_in_segment = true;
        while let Some(line) = lines.next_line()? {
            if line.is_empty() {
                bail!("empty complete rollout line");
            }
            let record: RolloutRecord =
                serde_json::from_slice(&line).context("parse complete rollout context record")?;
            let next = record
                .ordinal
                .checked_add(1)
                .ok_or_else(|| anyhow!("rollout ordinal overflow"))?;
            if first_in_segment {
                first_in_segment = false;
                if segment
                    .end
                    .as_ref()
                    .is_some_and(|position| position.end_ordinal_exclusive != next)
                {
                    bail!("lineage context boundary ordinal does not match its byte offset");
                }
            }
            if latest_ordinal.is_none() {
                if request
                    .position
                    .as_ref()
                    .is_some_and(|p| p.end_ordinal_exclusive != next)
                {
                    bail!("model context position ordinal does not match its byte boundary");
                }
                latest_ordinal = Some(next);
            }
            if previous_ordinal.is_some_and(|previous| next != previous) {
                bail!("rollout context ordinals are not contiguous");
            }
            previous_ordinal = Some(record.ordinal);
            scanned_records += 1;
            let is_context = matches!(
                &record.record,
                CanonicalRecord::ResponseItem(_) | CanonicalRecord::Compacted(_)
            );
            let is_checkpoint = matches!(&record.record, CanonicalRecord::Compacted(_));
            if is_context {
                let bytes = line.len().saturating_add(1);
                if records.len() >= request.max_records as usize
                    || used.saturating_add(bytes) > request.max_bytes as usize
                {
                    truncated = true;
                    break 'segments;
                }
                used += bytes;
                records.push(record);
                if is_checkpoint {
                    break 'segments;
                }
            }
            if (scanned_records >= MAX_CONTEXT_SCAN_RECORDS
                || scanned_bytes.saturating_add(lines.scanned_bytes) >= MAX_CONTEXT_SCAN_BYTES)
                && (lines.cursor > 0 || lines.buffer_end > 0 || segment_index > 0)
            {
                truncated = true;
                break 'segments;
            }
        }
        truncated |= lines.exhausted_budget;
        if lines.exhausted_budget {
            break 'segments;
        }
        scanned_bytes = scanned_bytes.saturating_add(lines.scanned_bytes);
        if previous_ordinal.is_some_and(|ordinal| ordinal != segment.start_ordinal) {
            bail!("lineage context is missing its initial record");
        }
    }
    if latest_ordinal.is_none()
        && request
            .position
            .as_ref()
            .is_some_and(|p| p.end_ordinal_exclusive != 0)
    {
        bail!("empty model context prefix has a nonempty ordinal position");
    }
    records.reverse();
    Ok(ModelContext {
        thread_id: request.thread_id,
        history_revision: revision(latest_ordinal.unwrap_or(0))?,
        records,
        truncated,
    })
}

fn history_request(
    cursor: Option<&OpaqueCursor>,
    stored: &StoredThread,
    turn: Option<&TurnId>,
    kind: &str,
    limit: u16,
) -> ThreadStoreResult<ThreadHistoryPageRequest> {
    let cursor: Option<HistoryCursor> = cursor.map(decode).transpose()?;
    if cursor.as_ref().is_some_and(|c| {
        c.rollout_id != stored.metadata.current_rollout_id
            || c.turn_id.as_ref() != turn
            || c.kind != kind
    }) {
        return Err(ThreadStoreError::Conflict {
            message: "history cursor does not match the requested page".into(),
        });
    }
    Ok(ThreadHistoryPageRequest {
        limit: limit as usize,
        before: cursor.map(|c| c.position),
    })
}

fn position(stored: &StoredThread, receipt: AppendReceipt) -> HistoryPosition {
    HistoryPosition {
        rollout_id: stored.metadata.current_rollout_id.clone(),
        end_ordinal_exclusive: receipt.next_ordinal,
        end_byte_offset: receipt.end_byte_offset,
    }
}

fn checked_rollout_path(root: &Path, path: &Path) -> Result<PathBuf> {
    // Canonicalize the nearest existing ancestor too: a compressed rollout's
    // logical plain path and a not-yet-created archive target do not exist.
    // On Windows mixing a verbatim canonical parent with a non-verbatim
    // missing path would otherwise fail a valid managed-root comparison.
    let path = canonicalize_existing_ancestor(path)?;
    let sessions = root.join("sessions");
    let archived = root.join("archived_sessions");
    let sessions = canonicalize_existing_ancestor(&sessions)?;
    let archived = canonicalize_existing_ancestor(&archived)?;
    if path.starts_with(&sessions) || path.starts_with(&archived) {
        let compressed = rollout_compression::compressed_path(&path);
        if compressed.try_exists()? {
            let physical = compressed.canonicalize()?;
            if !physical.starts_with(&sessions) && !physical.starts_with(&archived) {
                bail!("compressed rollout is outside the storage history roots");
            }
        }
        Ok(path)
    } else {
        bail!("rollout path is outside the storage history roots")
    }
}

fn canonicalize_existing_ancestor(path: &Path) -> Result<PathBuf> {
    let mut ancestor = path;
    let mut suffix = Vec::new();
    loop {
        match ancestor.canonicalize() {
            Ok(mut canonical) => {
                for name in suffix.into_iter().rev() {
                    canonical.push(name);
                }
                return Ok(canonical);
            }
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                suffix.push(
                    ancestor
                        .file_name()
                        .ok_or_else(|| anyhow!("managed path has no existing ancestor"))?
                        .to_os_string(),
                );
                ancestor = ancestor
                    .parent()
                    .ok_or_else(|| anyhow!("managed path has no existing ancestor"))?;
            }
            Err(error) => return Err(error.into()),
        }
    }
}

/// One resolver owns lineage traversal for every consumer. Metadata stores
/// immutable rollout identities; file moves only update their relative path.
pub(crate) fn resolve_lineage(
    conn: &Connection,
    root: &Path,
    thread: &ThreadId,
) -> Result<Vec<LineageSegment>> {
    let current: String = conn.query_row(
        "SELECT rollout_id FROM canonical_threads WHERE thread_id=?1",
        [thread.as_str()],
        |row| row.get(0),
    )?;
    let mut next = Some(current);
    let mut end = None;
    let mut seen = HashSet::new();
    let mut segments = Vec::new();
    while let Some(id) = next.take() {
        if segments.len() >= 64 {
            bail!("rollout lineage exceeds the maximum depth");
        }
        if !seen.insert(id.clone()) {
            bail!("rollout lineage contains a cycle");
        }
        let row: Option<(String,i64,Option<String>,Option<i64>,Option<i64>)> = conn.query_row(
            "SELECT rollout_path,start_ordinal,base_rollout_id,base_end_ordinal,base_end_byte_offset FROM canonical_rollouts WHERE rollout_id=?1",
            [&id], |row| Ok((row.get(0)?,row.get(1)?,row.get(2)?,row.get(3)?,row.get(4)?)),
        ).optional()?;
        let (relative, start, base, base_ordinal, base_offset) =
            row.ok_or_else(|| anyhow!("rollout lineage source is missing"))?;
        let relative = PathBuf::from(relative);
        if relative.is_absolute()
            || relative
                .components()
                .any(|part| !matches!(part, std::path::Component::Normal(_)))
        {
            bail!("invalid lineage rollout path");
        }
        let start = u64::try_from(start).context("invalid lineage start ordinal")?;
        if end
            .as_ref()
            .is_some_and(|position: &HistoryPosition| position.end_ordinal_exclusive <= start)
        {
            bail!("lineage range does not include its source metadata");
        }
        segments.push(LineageSegment {
            rollout_id: RolloutId::new(id)?,
            path: checked_rollout_path(root, &root.join(relative))?,
            start_ordinal: start,
            end,
        });
        end = if let Some(base) = base {
            let ordinal = u64::try_from(
                base_ordinal.ok_or_else(|| anyhow!("lineage source ordinal is missing"))?,
            )?;
            let offset = u64::try_from(
                base_offset.ok_or_else(|| anyhow!("lineage source offset is missing"))?,
            )?;
            if ordinal != start || offset == 0 {
                bail!("invalid lineage source boundary");
            }
            next = Some(base.clone());
            Some(HistoryPosition {
                rollout_id: RolloutId::new(base)?,
                end_ordinal_exclusive: ordinal,
                end_byte_offset: offset,
            })
        } else {
            if start != 0 {
                bail!("standalone rollout does not start at zero");
            }
            None
        };
    }
    segments.reverse();
    Ok(segments)
}

fn complete_read_boundary(reader: &mut RolloutReader) -> Result<HistoryPosition> {
    let mut cursor = reader.len();
    if cursor == 0 {
        bail!("rollout has no complete session metadata");
    }
    let mut final_newline = None;
    let mut scanned = 0usize;
    while cursor > 0 {
        let start = cursor.saturating_sub(CONTEXT_READ_BLOCK_BYTES as u64);
        let mut bytes = vec![0; (cursor - start) as usize];
        reader.seek(SeekFrom::Start(start))?;
        reader.read_exact(&mut bytes)?;
        if let Some(index) = bytes.iter().rposition(|byte| *byte == b'\n') {
            final_newline = Some(start + index as u64 + 1);
            break;
        }
        scanned += bytes.len();
        if scanned > ROLLOUT_MAX_RECORD_BYTES {
            bail!("incomplete rollout suffix exceeds its byte budget");
        }
        cursor = start;
    }
    let end = final_newline.ok_or_else(|| anyhow!("rollout has no complete record"))?;
    let record = last_record_at(reader, end)?;
    Ok(HistoryPosition {
        rollout_id: RolloutId::new("read-boundary")?,
        end_ordinal_exclusive: record
            .ordinal
            .checked_add(1)
            .ok_or_else(|| anyhow!("rollout ordinal overflow"))?,
        end_byte_offset: end,
    })
}

fn insert_rollout_row(
    conn: &Connection,
    metadata: &ThreadMetadata,
    relative: &str,
    base: Option<&HistoryPosition>,
) -> Result<()> {
    let start = base.map(|base| base.end_ordinal_exclusive).unwrap_or(0);
    conn.execute("INSERT INTO canonical_rollouts(rollout_id,owner_thread_id,rollout_path,created_at_ms,start_ordinal,base_rollout_id,base_end_ordinal,base_end_byte_offset) VALUES(?1,?2,?3,?4,?5,?6,?7,?8)",
        params![metadata.current_rollout_id.as_str(),metadata.thread_id.as_str(),relative,metadata.created_at_ms,i64::try_from(start)?,base.map(|base|base.rollout_id.as_str()),base.map(|base|i64::try_from(base.end_ordinal_exclusive)).transpose()?,base.map(|base|i64::try_from(base.end_byte_offset)).transpose()?])?;
    Ok(())
}

fn collect_unreferenced_rollouts(
    conn: &Connection,
    initial: &str,
) -> Result<Vec<(String, String)>> {
    let mut next = Some(initial.to_owned());
    let mut removed = Vec::new();
    while let Some(id) = next.take() {
        if removed.len() >= 64 {
            bail!("rollout garbage collection exceeds the lineage limit");
        }
        let referenced:bool=conn.query_row("SELECT EXISTS(SELECT 1 FROM canonical_threads WHERE rollout_id=?1) OR EXISTS(SELECT 1 FROM canonical_rollouts WHERE base_rollout_id=?1)",[&id],|row|row.get(0))?;
        if referenced {
            break;
        }
        let row: Option<(String, Option<String>)> = conn
            .query_row(
                "SELECT rollout_path,base_rollout_id FROM canonical_rollouts WHERE rollout_id=?1",
                [&id],
                |row| Ok((row.get(0)?, row.get(1)?)),
            )
            .optional()?;
        let Some((relative, parent)) = row else {
            break;
        };
        conn.execute("DELETE FROM canonical_rollouts WHERE rollout_id=?1", [&id])?;
        removed.push((id, relative));
        next = parent;
    }
    Ok(removed)
}

fn last_record_at(reader: &mut RolloutReader, end: u64) -> Result<RolloutRecord> {
    if end == 0 || end > reader.len() {
        bail!("history boundary is outside its rollout");
    }
    reader.seek(SeekFrom::Start(end - 1))?;
    let mut byte = [0];
    reader.read_exact(&mut byte)?;
    if byte[0] != b'\n' {
        bail!("history boundary is not a complete record");
    }
    let mut cursor = end - 1;
    let mut suffixes = Vec::new();
    let mut total = 0usize;
    loop {
        let start = cursor.saturating_sub(CONTEXT_READ_BLOCK_BYTES as u64);
        let mut bytes = vec![0; (cursor - start) as usize];
        reader.seek(SeekFrom::Start(start))?;
        reader.read_exact(&mut bytes)?;
        let boundary = bytes.iter().rposition(|byte| *byte == b'\n');
        let bytes = if let Some(index) = boundary {
            bytes.split_off(index + 1)
        } else {
            bytes
        };
        total += bytes.len();
        if total > ROLLOUT_MAX_RECORD_BYTES {
            bail!("rollout boundary record exceeds its byte budget");
        }
        suffixes.push(bytes);
        if boundary.is_some() || start == 0 {
            break;
        }
        cursor = start;
    }
    let mut line = Vec::with_capacity(total);
    for bytes in suffixes.into_iter().rev() {
        line.extend_from_slice(&bytes);
    }
    serde_json::from_slice(&line).context("parse history boundary record")
}

fn validate_history_boundary(reader: &mut RolloutReader, position: &HistoryPosition) -> Result<()> {
    let record = last_record_at(reader, position.end_byte_offset)?;
    if record.ordinal.checked_add(1) != Some(position.end_ordinal_exclusive) {
        bail!("history boundary ordinal does not match its byte offset");
    }
    Ok(())
}

fn find_completed_turn_boundary(
    segments: &[LineageSegment],
    turn: &TurnId,
) -> Result<HistoryPosition> {
    for segment in segments.iter().rev() {
        let stream = rollout_compression::open_rollout_stream(&segment.path)?;
        let limit = segment
            .end
            .as_ref()
            .map(|end| end.end_byte_offset)
            .unwrap_or(u64::MAX);
        let mut reader = BufReader::new(stream.take(limit));
        let mut offset = 0u64;
        let mut expected = segment.start_ordinal;
        loop {
            let mut line = Vec::new();
            let count = (&mut reader)
                .take(ROLLOUT_MAX_RECORD_BYTES as u64 + 1)
                .read_until(b'\n', &mut line)?;
            if count == 0 || line.last() != Some(&b'\n') {
                break;
            }
            if count > ROLLOUT_MAX_RECORD_BYTES {
                bail!("rollout record exceeds its byte budget");
            }
            let record: RolloutRecord = serde_json::from_slice(&line)?;
            if record.ordinal != expected {
                bail!("lineage rollout ordinals are not contiguous");
            }
            expected = expected
                .checked_add(1)
                .ok_or_else(|| anyhow!("rollout ordinal overflow"))?;
            offset = offset
                .checked_add(count as u64)
                .ok_or_else(|| anyhow!("rollout byte offset overflow"))?;
            if matches!(&record.record,CanonicalRecord::Event(CanonicalEvent::TurnCompleted{turn_id,..})|CanonicalRecord::Event(CanonicalEvent::TurnAborted{turn_id,..}) if turn_id==turn)
            {
                return Ok(HistoryPosition {
                    rollout_id: segment.rollout_id.clone(),
                    end_ordinal_exclusive: expected,
                    end_byte_offset: offset,
                });
            }
        }
    }
    bail!("completed turn is outside the visible lineage")
}

fn archive_path(root: &Path, source: &Path, archived: bool) -> Result<PathBuf> {
    let active = root.join("sessions");
    let cold = root.join("archived_sessions");
    let relative = if archived {
        source.strip_prefix(&active)
    } else {
        source.strip_prefix(&cold)
    }
    .map_err(|_| anyhow!("rollout path does not match its metadata status"))?;
    Ok(if archived {
        cold.join(relative)
    } else {
        active.join(relative)
    })
}

fn connect(path: &Path) -> Result<Connection> {
    let conn = Connection::open(path)?;
    conn.busy_timeout(Duration::from_secs(2))?;
    conn.execute_batch(
        "PRAGMA foreign_keys=ON; PRAGMA synchronous=NORMAL; PRAGMA cache_size=-1024;",
    )?;
    Ok(conn)
}

fn load_thread(path: &Path, root: &Path, id: &ThreadId) -> Result<Option<StoredThread>> {
    let conn = connect(path)?;
    let relative: Option<String> = conn
        .query_row(
            "SELECT rollout_path FROM canonical_threads WHERE thread_id=?1",
            [id.as_str()],
            |r| r.get(0),
        )
        .optional()?;
    let Some(relative) = relative else {
        return Ok(None);
    };
    let relative = PathBuf::from(relative);
    if relative.is_absolute()
        || relative
            .components()
            .any(|c| !matches!(c, std::path::Component::Normal(_)))
    {
        bail!("invalid metadata rollout path");
    }
    let mut stmt=conn.prepare("SELECT thread_id,rollout_id,status,created_at_ms,updated_at_ms,title,workspace_id,pinned FROM canonical_threads WHERE thread_id=?1")?;
    let rows = stmt.query([id.as_str()])?;
    let metadata = read_metadata(rows)?
        .pop()
        .ok_or_else(|| anyhow!("thread disappeared during read"))?;
    let descriptor = RolloutDescriptor {
        thread_id: metadata.thread_id.to_string(),
        rollout_id: metadata.current_rollout_id.to_string(),
        path: root.join(relative),
        created_at: Utc
            .timestamp_millis_opt(metadata.created_at_ms)
            .single()
            .ok_or_else(|| anyhow!("invalid thread creation timestamp"))?,
    };
    Ok(Some(StoredThread {
        metadata,
        descriptor,
    }))
}

fn read_metadata(mut rows: rusqlite::Rows<'_>) -> Result<Vec<ThreadMetadata>> {
    let mut entries = Vec::new();
    while let Some(row) = rows.next()? {
        entries.push(ThreadMetadata {
            thread_id: ThreadId::new(row.get::<_, String>(0)?)?,
            current_rollout_id: RolloutId::new(row.get::<_, String>(1)?)?,
            status: match row.get::<_, String>(2)?.as_str() {
                "archived" => ThreadStatus::Archived,
                "active" => ThreadStatus::Active,
                _ => bail!("invalid thread status"),
            },
            created_at_ms: row.get(3)?,
            updated_at_ms: row.get(4)?,
            title: row.get(5)?,
            workspace_id: row.get(6)?,
            pinned: row.get(7)?,
        });
    }
    Ok(entries)
}

fn status_name(status: ThreadStatus) -> &'static str {
    match status {
        ThreadStatus::Active => "active",
        ThreadStatus::Archived => "archived",
    }
}
fn unavailable(error: impl std::fmt::Display) -> ThreadStoreError {
    ThreadStoreError::Unavailable {
        message: error.to_string(),
    }
}
fn revision(value: u64) -> ThreadStoreResult<HistoryRevision> {
    HistoryRevision::new(value.to_string())
}
fn encode<T: Serialize>(value: &T) -> Result<OpaqueCursor> {
    use base64::Engine;
    Ok(OpaqueCursor::new(
        base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(serde_json::to_vec(value)?),
    )?)
}
fn decode<T: serde::de::DeserializeOwned>(cursor: &OpaqueCursor) -> ThreadStoreResult<T> {
    use base64::Engine;
    if cursor.as_str().len() > 4096 {
        return Err(ThreadStoreError::Conflict {
            message: "history cursor is too large".into(),
        });
    }
    let bytes = base64::engine::general_purpose::URL_SAFE_NO_PAD
        .decode(cursor.as_str())
        .map_err(unavailable)?;
    serde_json::from_slice(&bytes).map_err(unavailable)
}
async fn db<T: Send + 'static>(
    work: impl FnOnce() -> Result<T> + Send + 'static,
) -> ThreadStoreResult<T> {
    blocking::run_db("thread_store.state", work)
        .await
        .map_err(unavailable)
}

