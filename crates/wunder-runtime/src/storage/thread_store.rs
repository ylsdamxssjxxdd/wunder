    /// Targeted read-only recovery. The first access after opening the store
    /// checks this thread's durable suffix, never opens an append writer and
    /// never repairs/truncates a canonical file. Later pages only read SQLite.
    pub(crate) async fn ensure_history(&self, thread: &ThreadId) -> ThreadStoreResult<()> {
        self.recover_pending_revert_for_access(thread).await?;
        let stored = self.stored(thread).await?;
        let key = stored.descriptor.rollout_id.clone();
        if self.history_verified.lock().contains(&key) {
            return Ok(());
        }
        let gate = self.gate(thread)?;
        let _gate = gate.lock().await;
        if self.history_verified.lock().contains(&key) {
            return Ok(());
        }
        let segments = self.lineage_segments(thread).await?;
        let history = self.history.clone();
        blocking::run_fs("thread_store.ensure_history", move || {
            for segment in segments {
                let mut state = history.projection_state(segment.rollout_id.as_str())?;
                if segment
                    .end
                    .as_ref()
                    .is_some_and(|end| state.next_rollout_byte_offset >= end.end_byte_offset)
                {
                    continue;
                }
                if segment.end.is_none()
                    && state.next_rollout_byte_offset > 0
                    && rollout_compression::logical_rollout_len(&segment.path)?
                        == Some(state.next_rollout_byte_offset)
                {
                    continue;
                }
                let mut reader = rollout_compression::open_rollout_reader(&segment.path)?;
                let end = if let Some(end) = segment.end {
                    validate_history_boundary(&mut reader, &end)?;
                    end.end_byte_offset
                } else {
                    complete_read_boundary(&mut reader)?.end_byte_offset
                };
                // An ancestor can already be projected beyond the immutable
                // branch boundary. Scoped readers enforce that cutoff.
                while state.next_rollout_byte_offset < end {
                    let progress = history.project_reader_batch(
                        &mut reader,
                        segment.rollout_id.as_str(),
                        end,
                    )?;
                    if progress.records_projected == 0 {
                        bail!("history recovery did not advance");
                    }
                    state = progress.state;
                }
            }
            Ok(())
        })
        .await
        .map_err(unavailable)?;
        let mut verified = self.history_verified.lock();
        if verified.len() >= 4096 {
            verified.clear();
        }
        verified.insert(key);
        Ok(())
    }

    /// Explicit user-wide history deletion. Ownership is paged by its indexed
    /// key and each thread follows the same coordinated lifecycle as a single
    /// delete. A failure keeps remaining owner rows available for retry.
    pub(crate) async fn delete_user_threads(&self, user: &str) -> Result<i64> {
        if user.trim().is_empty() {
            return Ok(0);
        }
        let mut after = None::<String>;
        let mut removed = 0_i64;
        loop {
            let admissions = self.admission_store()?;
            let owner = user.to_owned();
            let cursor = after.clone();
            let ids =
                db(move || admissions.thread_ids_for_user(&owner, cursor.as_deref(), 64)).await?;
            if ids.is_empty() {
                return Ok(removed);
            }
            for id in ids {
                let thread = ThreadId::new(id.clone())?;
                let path = self.state_path.clone();
                let check = id.clone();
                let exists: bool = db(move || {
                    Ok(connect(&path)?.query_row(
                        "SELECT EXISTS(SELECT 1 FROM canonical_threads WHERE thread_id=?1)",
                        [check],
                        |row| row.get(0),
                    )?)
                })
                .await?;
                // Admission-only cleanup also stays inside the thread gate.
                self.delete_thread(&thread).await?;
                removed += i64::from(exists);
                after = Some(id);
            }
        }
    }

    pub async fn session_meta(&self, thread: &ThreadId) -> ThreadStoreResult<SessionMeta> {
        self.recover_pending_revert_for_access(thread).await?;
        self.session_meta_stored(self.stored(thread).await?).await
    }

    async fn session_meta_stored(&self, stored: StoredThread) -> ThreadStoreResult<SessionMeta> {
        blocking::run_fs("thread_store.session_meta", move || {
            let mut line = Vec::new();
            BufReader::new(rollout_compression::open_rollout_stream(
                stored.descriptor.path,
            )?)
            .take(ROLLOUT_MAX_RECORD_BYTES as u64 + 1)
            .read_until(b'\n', &mut line)?;
            if line.len() > ROLLOUT_MAX_RECORD_BYTES || line.last() != Some(&b'\n') {
                bail!("invalid session metadata record");
            }
            let record: RolloutRecord = serde_json::from_slice(&line)?;
            match record.record {
                CanonicalRecord::SessionMeta(meta) => Ok(meta),
                _ => bail!("rollout does not begin with session metadata"),
            }
        })
        .await
        .map_err(unavailable)
    }

    pub async fn history_position(&self, thread: &ThreadId) -> ThreadStoreResult<HistoryPosition> {
        self.recover_pending_revert_for_access(thread).await?;
        let stored = self.stored(thread).await?;
        let history = self.history.clone();
        db(move || {
            let state = history.projection_state(&stored.descriptor.rollout_id)?;
            Ok(HistoryPosition {
                rollout_id: stored.metadata.current_rollout_id,
                end_ordinal_exclusive: state.next_rollout_ordinal,
                end_byte_offset: state.next_rollout_byte_offset,
            })
        })
        .await
    }

