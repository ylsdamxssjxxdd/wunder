fn build_zip_package(entries: &[(&str, &str)]) -> Result<Vec<u8>, String> {
    let cursor = std::io::Cursor::new(Vec::new());
    let mut zip = zip::ZipWriter::new(cursor);
    let options = FileOptions::default().compression_method(CompressionMethod::Deflated);
    for (name, content) in entries {
        zip.start_file(*name, options)
            .map_err(|err| format!("create template entry failed: {err}"))?;
        zip.write_all(content.as_bytes())
            .map_err(|err| format!("write template entry failed: {err}"))?;
    }
    let cursor = zip
        .finish()
        .map_err(|err| format!("finalize template archive failed: {err}"))?;
    Ok(cursor.into_inner())
}

#[cfg(test)]
mod tests {
    use super::build_workspace_file_template;

    #[test]
    fn builds_minimal_xlsx_template_for_empty_new_file() {
        let bytes = build_workspace_file_template("sheet.xlsx", "").expect("xlsx template");
        assert!(bytes.starts_with(b"PK"));
        assert!(bytes.len() > 100);
    }

    #[test]
    fn keeps_text_content_unmodified_for_non_empty_requests() {
        assert!(build_workspace_file_template("sheet.xlsx", "hello").is_none());
    }

    #[test]
    fn builds_valid_minimal_pptx_template_for_empty_new_file() {
        use std::io::Read;

        let bytes = build_workspace_file_template("slides.pptx", "").expect("pptx template");
        assert!(bytes.starts_with(b"PK"));

        let mut archive =
            zip::ZipArchive::new(std::io::Cursor::new(bytes)).expect("valid pptx zip package");
        let required = [
            "ppt/presentation.xml",
            "ppt/_rels/presentation.xml.rels",
            "ppt/slideMasters/slideMaster1.xml",
            "ppt/slideMasters/_rels/slideMaster1.xml.rels",
            "ppt/slideLayouts/slideLayout1.xml",
            "ppt/slideLayouts/_rels/slideLayout1.xml.rels",
            "ppt/slides/slide1.xml",
            "ppt/slides/_rels/slide1.xml.rels",
            "ppt/theme/theme1.xml",
        ];
        for name in required {
            assert!(
                archive.by_name(name).is_ok(),
                "minimal pptx is missing required part: {name}"
            );
        }

        let mut presentation = String::new();
        archive
            .by_name("ppt/presentation.xml")
            .unwrap()
            .read_to_string(&mut presentation)
            .unwrap();
        assert!(
            presentation.contains("<p:sldMasterIdLst>"),
            "presentation.xml must reference a slide master"
        );
        assert!(
            presentation.contains("<p:sldMasterId id=\"2147483648\" r:id=\"rId2\"/>"),
            "presentation.xml must bind the slide master relationship"
        );

        let mut content_types = String::new();
        archive
            .by_name("[Content_Types].xml")
            .unwrap()
            .read_to_string(&mut content_types)
            .unwrap();
        assert!(content_types.contains("slideMaster+xml"));
        assert!(content_types.contains("slideLayout+xml"));
        assert!(content_types.contains("theme+xml"));
    }
}
