//! Build-time generator for the workspace file-icon textures.
//!
//! 桌面版 and 安卓版 show the same file icons: 桌面版's workspace panel, the
//! document cards in its transcript, and 安卓版's transcript cards all resolve
//! through this one table. Keeping the generator here means the two build
//! scripts cannot drift apart — `assets/vscode-icons/file-icon-map.json` (synced
//! by `scripts/sync_desktop_file_icons.py`) stays the single source of truth.
//!
//! The generator emits, into `OUT_DIR`:
//!
//! * one PNG texture per referenced icon (SVG icons rasterized at 2x so the
//!   software renderer downscales crisply at list/card sizes);
//! * `file_icons_data.rs`, included by the consuming crate's `file_icons`
//!   module, with the byte table plus the extension/file-name lookup tables.
//!
//! All paths in the emitted file are relative to `OUT_DIR`, so the consumer
//! only has to `include!` it.

use std::path::Path;

/// Icon asset root expected by [`write_workspace_icons`]: a directory holding
/// `vscode-icons/file-icon-map.json`, the SVG files that map references, and
/// `doc-icons/{folder,processon_flow}.png`.
///
/// `out_dir` must be the consuming build script's `OUT_DIR`. Panics on any
/// missing or malformed input: a silent fallback would ship wrong icons.
pub fn write_workspace_icons(assets: &Path, out_dir: &Path) {
    let map: serde_json::Value = serde_json::from_str(
        &String::from_utf8(read_required(&assets.join("vscode-icons/file-icon-map.json")))
            .expect("parse file-icon-map.json"),
    )
    .expect("parse file-icon-map.json");
    let default_icon = icon_value(&map["default"]);
    let folder_icon = icon_value(&map["folder"]);
    let diagram_icon = icon_value(&map["diagram"]);

    let mut referenced: Vec<String> = vec![default_icon.clone()];
    for table in ["extensions", "names"] {
        for value in map[table].as_object().expect("icon table").values() {
            referenced.push(icon_value(value));
        }
    }
    referenced.sort();
    referenced.dedup();
    for name in &referenced {
        let key = png_key(name);
        let svg = read_required(&assets.join("vscode-icons").join(name));
        write_texture(out_dir, &key, &rasterize_svg(&svg));
    }
    for name in [&folder_icon, &diagram_icon] {
        let bytes = read_required(&assets.join("doc-icons").join(name));
        write_texture(out_dir, name, &bytes);
    }

    let mut data = String::from(
        "// @generated by wunder-icon-builder from assets/vscode-icons/file-icon-map.json;\n\
         // re-sync via scripts/sync_desktop_file_icons.py. Do not edit.\n",
    );
    data.push_str("pub(crate) static ICON_BYTES: &[(&str, &[u8])] = &[\n");
    for name in &referenced {
        let key = png_key(name);
        data.push_str(&format!("    ({key:?}, include_bytes!({key:?})),\n"));
    }
    for name in [&folder_icon, &diagram_icon] {
        data.push_str(&format!("    ({name:?}, include_bytes!({name:?})),\n"));
    }
    data.push_str("];\n");
    emit_table(&mut data, "EXTENSIONS", &map["extensions"], true);
    emit_table(&mut data, "NAMES", &map["names"], true);
    emit_table(
        &mut data,
        "DIAGRAM_EXTENSIONS",
        &map["diagram-extensions"],
        false,
    );
    data.push_str(&format!(
        "pub(crate) const DEFAULT_ICON: &str = {:?};\n\
         pub(crate) const FOLDER_ICON: &str = {:?};\n\
         pub(crate) const DIAGRAM_ICON: &str = {:?};\n",
        png_key(&default_icon),
        png_key(&folder_icon),
        png_key(&diagram_icon),
    ));
    std::fs::write(out_dir.join("file_icons_data.rs"), data).expect("write file_icons_data.rs");
}

fn emit_table(data: &mut String, name: &str, value: &serde_json::Value, keyed: bool) {
    if keyed {
        let mut rows: Vec<(String, String)> = value
            .as_object()
            .expect("keyed icon table")
            .iter()
            .map(|(key, value)| (key.clone(), icon_value(value)))
            .collect();
        rows.sort_by(|a, b| a.0.cmp(&b.0));
        data.push_str(&format!("pub(crate) static {name}: &[(&str, &str)] = &[\n"));
        for (key, icon) in rows {
            data.push_str(&format!("    ({key:?}, {:?}),\n", png_key(&icon)));
        }
    } else {
        let mut items: Vec<String> = value
            .as_array()
            .expect("icon list")
            .iter()
            .map(|item| item.as_str().expect("icon key").to_owned())
            .collect();
        items.sort();
        data.push_str(&format!("pub(crate) static {name}: &[&str] = &[\n"));
        for item in items {
            data.push_str(&format!("    {item:?},\n"));
        }
    }
    data.push_str("];\n");
}

fn icon_value(value: &serde_json::Value) -> String {
    value.as_str().expect("icon file name").to_owned()
}

/// Icon table keys reference textures by their PNG name.
fn png_key(icon: &str) -> String {
    match icon.strip_suffix(".svg") {
        Some(stem) => format!("{stem}.png"),
        None => icon.to_owned(),
    }
}

fn read_required(path: &Path) -> Vec<u8> {
    std::fs::read(path).unwrap_or_else(|error| panic!("read {}: {error}", path.display()))
}

fn write_texture(out_dir: &Path, key: &str, bytes: &[u8]) {
    std::fs::write(out_dir.join(key), bytes)
        .unwrap_or_else(|error| panic!("write {key}: {error}"));
}

/// Render an SVG at 2x so the software renderer downscales crisply at the
/// 12-20px sizes the file lists use. resvg outputs premultiplied alpha; the
/// runtime decodes straight alpha, so convert before encoding.
fn rasterize_svg(svg: &[u8]) -> Vec<u8> {
    let tree = resvg::usvg::Tree::from_data(svg, &resvg::usvg::Options::default())
        .expect("parse workspace icon svg");
    let size = tree.size();
    let scale = 2.0f32;
    let width = (size.width() * scale).round() as u32;
    let height = (size.height() * scale).round() as u32;
    let mut pixmap = resvg::tiny_skia::Pixmap::new(width, height).expect("icon pixmap");
    resvg::render(
        &tree,
        resvg::tiny_skia::Transform::from_scale(scale, scale),
        &mut pixmap.as_mut(),
    );
    let mut straight = pixmap.data().to_vec();
    for pixel in straight.chunks_exact_mut(4) {
        let alpha = pixel[3];
        if alpha == 0 {
            pixel[..3].fill(0);
        } else if alpha != 255 {
            for channel in &mut pixel[..3] {
                *channel = (((*channel as u32) * 255 + alpha as u32 / 2) / alpha as u32) as u8;
            }
        }
    }
    let mut encoded = Vec::new();
    let mut encoder = png::Encoder::new(&mut encoded, width, height);
    encoder.set_color(png::ColorType::Rgba);
    encoder.set_depth(png::BitDepth::Eight);
    encoder
        .write_header()
        .expect("png header")
        .write_image_data(&straight)
        .expect("png data");
    encoded
}
