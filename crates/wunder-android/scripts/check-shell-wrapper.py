#!/usr/bin/env python3
"""Verify the 安卓版 proot shell wrapper against the command tool's launch contract.

The wrapper is generated by `UbuntuRuntime.writeWrapper()` and sits between the
engine's `/system/bin/sh` and the guest shell. Two generations of it run on user
devices, and the command channel has to work with both:

  * legacy wrappers read the script from argv (`$2`) and then reset the guest
    environment with `env -i`, which drops every `WUNDER_*` variable;
  * current wrappers prefer `WUNDER_COMMAND_SCRIPT`, so user text never lands in
    argv, where `pkill -f` would match the wrapper itself.

The engine therefore stages the script in a file under the app's `<files>/tmp`
(bind-mounted into the guest at the same path) and passes a one-line launcher
that sources it. This check feeds that launcher to the wrapper generated by the
current Java source *and* to a frozen legacy fixture, on the host, with a `proot`
stub — no Android SDK or device needed:

    python3 crates/wunder-android/scripts/check-shell-wrapper.py
"""

from __future__ import annotations

import os
import pathlib
import re
import subprocess
import sys
import tempfile

REPO = pathlib.Path(__file__).resolve().parents[3]
JAVA = REPO / "crates/wunder-android/android/app/src/main/java/dev/wunder/android/UbuntuRuntime.java"

# The wrapper is `header + <shell lines...> + proot + "<guest wd>" + <env args>`.
# Only `header` and `proot` are Java expressions; everything else is literal.
PLACEHOLDER = "\x00EXPR\x00"

ESCAPES = {"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\", "'": "'"}

# Frozen copy of the wrapper shipped before the environment channel. Kept as a
# fixture on purpose: it is the generation that still sits in app-private files
# on devices that installed an older build, and the launcher must keep working
# there. Its two decisive properties are `CMD="$2"` (argv only) and `env -i`
# (resets the guest environment).
LEGACY_WRAPPER = """#!/bin/sh
CMD="$2"
if [ "$1" != "-lc" ]; then CMD="$*"; fi
HOST_WD=$(pwd -P 2>/dev/null || pwd)
GUEST_WD="/root"
case "$HOST_WD" in
  "$HARNESS_FILES"*|/data/data/*|/storage/*|/sdcard*|/data/local/tmp*) GUEST_WD="$HOST_WD" ;;
esac
exec "$HARNESS_PROOT" -0 -r "$HARNESS_ROOTFS" -w "$GUEST_WD" \\
  /usr/bin/env -i HOME=/root TERM=dumb LANG=C.UTF-8 \\
  PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin \\
  WUNDER_UBUNTU=1 \\
  /bin/bash -lc "$CMD"
"""


def java_literal(body: str) -> str:
    out = []
    index = 0
    while index < len(body):
        char = body[index]
        if char == "\\" and index + 1 < len(body):
            out.append(ESCAPES.get(body[index + 1], body[index + 1]))
            index += 2
            continue
        out.append(char)
        index += 1
    return "".join(out)


def wrapper_script(source: str) -> str:
    """Rebuild the generated wrapper text, substituting the host-side paths."""
    start = source.index("String shellScript = ")
    body = source[start:source.index(";\n", start)].split("=", 1)[1]
    parts = []
    for piece in re.split(r"\s*\+\s*", body):
        piece = piece.strip()
        if piece.startswith('"'):
            parts.append(java_literal(piece[1:-1]))
        else:
            parts.append(PLACEHOLDER)
    if parts.count(PLACEHOLDER) != 2:
        raise SystemExit(
            "check-shell-wrapper: cannot parse shellScript in UbuntuRuntime.java "
            f"({parts.count(PLACEHOLDER)} expressions, expected 2)"
        )

    header = (
        "#!/bin/sh\n"
        'BIN="$HARNESS_BIN"\n'
        'ROOTFS="$HARNESS_ROOTFS"\n'
        'FILES="$HARNESS_FILES"\n'
        'TMP="$HARNESS_FILES/tmp"\n'
        'FLAGS=""\n'
    )
    proot = '"$HARNESS_PROOT" -0 -r "$ROOTFS" $FLAGS $BINDS -w '

    script = []
    expression = 0
    for part in parts:
        if part is PLACEHOLDER:
            script.append(header if expression == 0 else proot)
            expression += 1
        else:
            script.append(part)
    return "".join(script)


def stub_proot(directory: pathlib.Path) -> pathlib.Path:
    """Stand-in for proot: drop its own options, exec the guest command."""
    path = directory / "proot"
    path.write_text(
        "#!/bin/sh\n"
        "while [ $# -gt 0 ]; do\n"
        '  case "$1" in\n'
        "    /usr/bin/env*) break ;;\n"
        "    -r|-b|-w) shift 2 ;;\n"
        "    *) shift ;;\n"
        "  esac\n"
        "done\n"
        '[ $# -gt 0 ] || { echo "stub proot: no guest command" >&2; exit 127; }\n'
        'exec "$@"\n',
        encoding="utf-8",
    )
    path.chmod(0o755)
    return path


def launcher(script_path: pathlib.Path) -> str:
    """Exactly what `command_utils::staged_script_launch` builds."""
    return f'. "{script_path}"; wunder_rc=$?; rm -f "{script_path}"; exit $wunder_rc'


class Sandbox:
    def __init__(self, root: pathlib.Path) -> None:
        self.root = root
        for name in ("bin", "rootfs", "files/tmp", "home"):
            (root / name).mkdir(parents=True, exist_ok=True)
        self.proot = stub_proot(root)

    def env(self, script_env: str | None) -> dict:
        env = dict(os.environ)
        env.update(
            HARNESS_BIN=str(self.root / "bin"),
            HARNESS_ROOTFS=str(self.root / "rootfs"),
            HARNESS_FILES=str(self.root / "files"),
            HARNESS_PROOT=str(self.proot),
            HOME=str(self.root / "home"),
        )
        env.pop("WUNDER_COMMAND_SCRIPT", None)
        if script_env is not None:
            env["WUNDER_COMMAND_SCRIPT"] = script_env
        return env

    def wrapper(self, text: str, name: str) -> pathlib.Path:
        path = self.root / "bin" / name
        path.write_text(text, encoding="utf-8")
        path.chmod(0o755)
        return path

    def stage(self, script: str, index: int) -> pathlib.Path:
        path = self.root / "files" / "tmp" / f"wunder-cmd-{os.getpid()}-{index}.sh"
        path.write_text(script, encoding="utf-8")
        path.chmod(0o600)
        return path


def run_staged(sandbox: Sandbox, wrapper: pathlib.Path, script: str) -> tuple:
    """Invoke the wrapper exactly like the engine does today."""
    staged = sandbox.stage(script, 0)
    launch = launcher(staged)
    done = subprocess.run(
        ["/bin/sh", str(wrapper), "-lc", launch],
        env=sandbox.env(launch),
        capture_output=True,
        text=True,
        timeout=60,
    )
    return done.returncode, done.stdout, done.stderr, staged.exists()


def run_inline(sandbox: Sandbox, wrapper: pathlib.Path, script: str) -> tuple:
    """The pre-staging channel: whole script inline in the environment."""
    done = subprocess.run(
        ["/bin/sh", str(wrapper), "-lc", 'eval "${WUNDER_COMMAND_SCRIPT}"'],
        env=sandbox.env(script),
        capture_output=True,
        text=True,
        timeout=60,
    )
    return done.returncode, done.stdout, done.stderr


def check_launcher(label: str, sandbox: Sandbox, wrapper: pathlib.Path) -> list[str]:
    failures = []
    marker = sandbox.root / "files" / "ran"

    code, out, err, left_behind = run_staged(
        sandbox, wrapper, f"set -o pipefail; echo WRAPPER_OK; touch {marker}"
    )
    if code != 0 or "WRAPPER_OK" not in out or not marker.exists():
        failures.append(
            f"[{label}] launch lost the command "
            f"(exit={code}, stdout={out!r}, stderr={err!r}, marker={marker.exists()})"
        )
    if left_behind:
        failures.append(f"[{label}] the guest did not remove its staged script")

    code, out, err, _ = run_staged(
        sandbox, wrapper, "set -o pipefail; echo 'a b' | tr ' ' '_'; echo \"$LANG\""
    )
    if out.split() != ["a_b", "C.UTF-8"]:
        failures.append(f"[{label}] quoting/newlines: unexpected output {out!r} (stderr={err!r})")

    return failures


def main() -> int:
    failures = []
    with tempfile.TemporaryDirectory(prefix="wunder-shell-check-") as tmp:
        current = Sandbox(pathlib.Path(tmp) / "current")
        generated = current.wrapper(wrapper_script(JAVA.read_text(encoding="utf-8")), "wunder-shell")
        failures += check_launcher("current wrapper", current, generated)

        legacy = Sandbox(pathlib.Path(tmp) / "legacy")
        frozen = legacy.wrapper(LEGACY_WRAPPER, "wunder-shell")
        failures += check_launcher("legacy wrapper", legacy, frozen)
        # The fixture has to reproduce the historical breakage, otherwise the
        # legacy case above proves nothing.
        code, out, _ = run_inline(legacy, frozen, "echo INLINE_OK")
        if code != 0 or "INLINE_OK" in out:
            failures.append(
                "[legacy wrapper] fixture no longer drops the environment "
                f"(exit={code}, stdout={out!r}) — update the fixture"
            )

    if failures:
        print("check-shell-wrapper: FAILED", file=sys.stderr)
        for failure in failures:
            print(f"  - {failure}", file=sys.stderr)
        return 1
    print("check-shell-wrapper: ok")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
