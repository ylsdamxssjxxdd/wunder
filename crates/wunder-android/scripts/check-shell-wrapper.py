#!/usr/bin/env python3
"""Verify the 安卓版 proot shell wrapper against the command tool's contract.

The wrapper is generated by `UbuntuRuntime.writeWrapper()` and sits between the
engine's `/system/bin/sh` and the guest shell. It only works while both sides
agree on how the script travels:

  * the engine passes `-lc 'eval "${WUNDER_COMMAND_SCRIPT}"'` and puts the real
    script in the `WUNDER_COMMAND_SCRIPT` environment variable (see
    `command_utils::build_shell_command_with_shell`);
  * the wrapper has to forward that variable past its own `env -i`, otherwise
    the guest evaluates an empty script: exit 0, no output, no side effects.

That mismatch already shipped once and looked like "the shell is broken" on the
phone, so this check rebuilds the wrapper straight from the Java source and runs
it on the host with a `proot` stub. No Android SDK or device needed:

    python3 crates/wunder-android/scripts/check-shell-wrapper.py
"""

from __future__ import annotations

import os
import pathlib
import re
import subprocess
import sys
import tempfile

REPO = pathlib.Path(__file__).resolve().parents[3]
JAVA = REPO / "crates/wunder-android/android/app/src/main/java/dev/wunder/android/UbuntuRuntime.java"

# The wrapper is `header + <shell lines...> + proot + "<guest wd>" + <env args>`.
# Only `header` and `proot` are Java expressions; everything else is literal and
# is what this check exercises.
PLACEHOLDER = "\x00EXPR\x00"

ESCAPES = {"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\", "'": "'"}


def java_literal(body: str) -> str:
    out = []
    index = 0
    while index < len(body):
        char = body[index]
        if char == "\\" and index + 1 < len(body):
            out.append(ESCAPES.get(body[index + 1], body[index + 1]))
            index += 2
            continue
        out.append(char)
        index += 1
    return "".join(out)


def wrapper_script(source: str) -> str:
    """Rebuild the generated wrapper text, substituting the host-side paths."""
    start = source.index("String shellScript = ")
    body = source[start:source.index(";\n", start)].split("=", 1)[1]
    parts = []
    for piece in re.split(r"\s*\+\s*", body):
        piece = piece.strip()
        if piece.startswith('"'):
            parts.append(java_literal(piece[1:-1]))
        else:
            parts.append(PLACEHOLDER)
    if parts.count(PLACEHOLDER) != 2:
        raise SystemExit(
            "check-shell-wrapper: cannot parse shellScript in UbuntuRuntime.java "
            f"({parts.count(PLACEHOLDER)} expressions, expected 2)"
        )

    header = (
        "#!/bin/sh\n"
        'BIN="$HARNESS_BIN"\n'
        'ROOTFS="$HARNESS_ROOTFS"\n'
        'FILES="$HARNESS_FILES"\n'
        'TMP="$HARNESS_FILES/tmp"\n'
        'FLAGS=""\n'
    )
    proot = '"$HARNESS_PROOT" -0 -r "$ROOTFS" $FLAGS $BINDS -w '

    # Only `header` (first) and `proot` (second) are Java expressions; every
    # other part is literal source text and is what this check exercises.
    script = []
    expression = 0
    for part in parts:
        if part is PLACEHOLDER:
            script.append(header if expression == 0 else proot)
            expression += 1
        else:
            script.append(part)
    return "".join(script)


def stub_proot(directory: pathlib.Path) -> pathlib.Path:
    """Stand-in for proot: drop its own options, exec the guest command."""
    path = directory / "proot"
    path.write_text(
        "#!/bin/sh\n"
        "while [ $# -gt 0 ]; do\n"
        '  case "$1" in\n'
        "    /usr/bin/env*) break ;;\n"
        "    -r|-b|-w) shift 2 ;;\n"
        "    *) shift ;;\n"
        "  esac\n"
        "done\n"
        '[ $# -gt 0 ] || { echo "stub proot: no guest command" >&2; exit 127; }\n'
        'exec "$@"\n',
        encoding="utf-8",
    )
    path.chmod(0o755)
    return path


def run(wrapper: pathlib.Path, sandbox: pathlib.Path, command: str | None) -> tuple:
    """Invoke the wrapper exactly like the engine does."""
    argv = ["/bin/sh", str(wrapper), "-lc", 'eval "${WUNDER_COMMAND_SCRIPT}"']
    env = dict(os.environ)
    env.update(
        HARNESS_BIN=str(sandbox),
        HARNESS_ROOTFS=str(sandbox / "rootfs"),
        HARNESS_FILES=str(sandbox / "files"),
        HARNESS_PROOT=str(sandbox / "proot"),
        HOME=str(sandbox / "home"),
    )
    env.pop("WUNDER_COMMAND_SCRIPT", None)
    if command is None:
        argv[3] = "echo FALLBACK"
    else:
        env["WUNDER_COMMAND_SCRIPT"] = command
    done = subprocess.run(argv, env=env, capture_output=True, text=True, timeout=60)
    return done.returncode, done.stdout, done.stderr


def main() -> int:
    java = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else JAVA
    source = java.read_text(encoding="utf-8")
    failures = []

    with tempfile.TemporaryDirectory(prefix="wunder-shell-check-") as tmp:
        sandbox = pathlib.Path(tmp)
        for name in ("rootfs", "files/tmp", "home"):
            (sandbox / name).mkdir(parents=True, exist_ok=True)
        stub_proot(sandbox)
        wrapper = sandbox / "wunder-shell"
        wrapper.write_text(wrapper_script(source), encoding="utf-8")
        wrapper.chmod(0o755)

        marker = sandbox / "files" / "ran"
        code, out, err = run(wrapper, sandbox, f"echo WRAPPER_OK; touch {marker}")
        if code != 0 or "WRAPPER_OK" not in out or not marker.exists():
            failures.append(
                "env contract: the wrapper dropped WUNDER_COMMAND_SCRIPT "
                f"(exit={code}, stdout={out!r}, stderr={err!r}, marker={marker.exists()})"
            )

        code, out, err = run(wrapper, sandbox, "echo 'a b' | tr ' ' '_'; echo \"$LANG\"")
        if out.split() != ["a_b", "C.UTF-8"]:
            failures.append(
                f"quoting/newlines: unexpected output {out!r} (exit={code}, stderr={err!r})"
            )

        code, out, err = run(wrapper, sandbox, None)
        if code != 0 or "FALLBACK" not in out:
            failures.append(
                "positional fallback: `-lc <command>` without the env var broke "
                f"(exit={code}, stdout={out!r}, stderr={err!r})"
            )

    if failures:
        print("check-shell-wrapper: FAILED", file=sys.stderr)
        for failure in failures:
            print(f"  - {failure}", file=sys.stderr)
        return 1
    print("check-shell-wrapper: ok")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
