#!/usr/bin/env python3
"""Maintain the local Slint vendor patch queue.

The vendor directories are still the build source of truth.  This script makes
their upstream-relative changes reviewable and replayable as a quilt-like
series of small, per-file patches:

    python scripts/slint_vendor_patches.py export
    python scripts/slint_vendor_patches.py verify
    python scripts/slint_vendor_patches.py apply --upstream-root <new-src> --out <staging>
    python scripts/slint_vendor_patches.py capture --upstream-root <new-src> --vendor <staging> --patch-dir <new-series>

`export` reads `vendor/upstreams.json`, downloads the pinned
crates.io sources when no `--upstream-root` is supplied, and writes patches
under `vendor/patches/<base>`.  `verify` applies that queue to a
fresh copy of the same pristine sources and checks that it reproduces the
vendor tree byte-for-byte (ignoring Cargo's generated metadata files).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path, PurePosixPath


ROOT = Path(__file__).resolve().parents[1]
VENDOR_ROOT = ROOT / "vendor"
DEFAULT_MANIFEST = VENDOR_ROOT / "upstreams.json"
WORK_ROOT = ROOT / "target" / "slint-vendor-work"

# These are generated by Cargo when a crate is vendored.  They are not source
# patches and would make the series noisy without affecting compilation.
IGNORED_NAMES = {".cargo-ok", "Cargo.toml.orig"}
GIT = shutil.which("git") or "git"
# The repository may have core.autocrlf=true, but the vendored Rust sources are
# LF.  Force both diff generation and patch application to byte-preserving LF so
# `verify` compares the actual patch result rather than a CRLF conversion.
GIT_CONFIG = ["-c", "core.autocrlf=false", "-c", "core.safecrlf=false"]


class PatchQueueError(RuntimeError):
    pass


def log(message: str) -> None:
    print(message, flush=True)


def run(command: list[str], *, cwd: Path | None = None) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        command,
        cwd=str(cwd) if cwd else None,
        text=True,
        encoding="utf-8",
        errors="replace",
        capture_output=True,
    )


def run_raw(command: list[str], *, cwd: Path | None = None) -> subprocess.CompletedProcess[bytes]:
    return subprocess.run(
        command,
        cwd=str(cwd) if cwd else None,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_manifest(path: Path) -> dict:
    if not path.is_file():
        raise PatchQueueError(f"manifest not found: {path}")
    data = json.loads(path.read_text(encoding="utf-8"))
    crates = data.get("crates")
    if not isinstance(crates, list) or not crates:
        raise PatchQueueError(f"manifest has no crates: {path}")
    for crate in crates:
        for key in ("name", "version", "vendor"):
            if not crate.get(key):
                raise PatchQueueError(f"manifest crate missing {key}: {crate!r}")
    if not data.get("slint_version"):
        raise PatchQueueError(f"manifest has no slint_version: {path}")
    return data


def patch_dir_from(manifest: dict, override: str | None) -> Path:
    if override:
        return Path(override).resolve()
    relative = manifest.get("patch_dir")
    if not relative:
        raise PatchQueueError("manifest has no patch_dir")
    return (VENDOR_ROOT / relative).resolve()


def safe_extract(archive: Path, destination: Path) -> None:
    destination.mkdir(parents=True, exist_ok=True)
    with tarfile.open(archive, "r:gz") as tar:
        for member in tar.getmembers():
            member_path = PurePosixPath(member.name)
            if member_path.is_absolute() or ".." in member_path.parts:
                raise PatchQueueError(f"unsafe archive member: {member.name}")
        try:
            tar.extractall(destination, filter="data")
        except TypeError:
            # Python < 3.12 has no extraction filter; the explicit path check
            # above still prevents traversal outside the destination.
            tar.extractall(destination)


def download_sources(manifest: dict) -> dict[str, Path]:
    """Download and verify the pinned crates.io archives, then extract them."""
    cache = WORK_ROOT / manifest["slint_version"]
    archive_dir = cache / "archives"
    source_dir = cache / "sources"
    archive_dir.mkdir(parents=True, exist_ok=True)
    sources: dict[str, Path] = {}

    for crate in manifest["crates"]:
        name = crate["name"]
        version = crate["version"]
        archive = archive_dir / f"{name}-{version}.crate"
        expected = crate.get("sha256")
        if not archive.is_file():
            url = f"https://crates.io/api/v1/crates/{name}/{version}/download"
            log(f"download {name} {version}")
            request = urllib.request.Request(url, headers={"User-Agent": "rcho-vendor-maintainer/1"})
            with urllib.request.urlopen(request, timeout=120) as response, archive.open("wb") as output:
                shutil.copyfileobj(response, output)
        if expected and sha256(archive) != expected:
            raise PatchQueueError(f"sha256 mismatch for {archive}; remove it and retry")

        destination = source_dir / f"{name}-{version}"
        marker = destination / f"{name}-{version}" / "Cargo.toml"
        if not marker.is_file():
            log(f"extract {archive.name}")
            if destination.exists():
                shutil.rmtree(destination)
            safe_extract(archive, destination)
        source = find_crate_dir(destination, name, version)
        sources[name] = source
        log(f"source {name}: {source}")
    return sources


def find_crate_dir(root: Path, name: str, version: str | None = None) -> Path:
    exact = root / f"{name}-{version}" if version else root / name
    if exact.is_dir() and (exact / "Cargo.toml").is_file():
        return exact

    candidates = [
        path
        for path in root.rglob(f"{name}-*")
        if path.is_dir() and (path / "Cargo.toml").is_file() and path.name.startswith(f"{name}-")
    ]
    if version:
        versioned = [path for path in candidates if path.name == f"{name}-{version}"]
        if len(versioned) == 1:
            return versioned[0]
        candidates = versioned or candidates
    if len(candidates) == 1:
        return candidates[0]
    if not candidates:
        raise PatchQueueError(f"could not find pristine source for {name} under {root}")
    listing = ", ".join(str(path.relative_to(root)) for path in candidates[:8])
    raise PatchQueueError(f"ambiguous pristine source for {name} under {root}: {listing}")


def sources_from_root(root: Path, manifest: dict) -> dict[str, Path]:
    sources: dict[str, Path] = {}
    for crate in manifest["crates"]:
        source = find_crate_dir(root, crate["name"])
        sources[crate["name"]] = source
        log(f"source {crate['name']}: {source}")
    return sources


def relative_files(root: Path) -> dict[str, Path]:
    files: dict[str, Path] = {}
    for path in root.rglob("*"):
        if path.is_file() and not path.is_symlink():
            files[path.relative_to(root).as_posix()] = path
    return files


def ignored(relative: str) -> bool:
    return Path(relative).name in IGNORED_NAMES


def changed_files(pristine: Path, vendor: Path) -> list[tuple[str, str]]:
    pristine_files = relative_files(pristine)
    vendor_files = relative_files(vendor)
    changes: list[tuple[str, str]] = []
    for relative in sorted(set(pristine_files) | set(vendor_files)):
        if ignored(relative):
            continue
        before = pristine_files.get(relative)
        after = vendor_files.get(relative)
        if before is None:
            changes.append((relative, "added"))
        elif after is None:
            changes.append((relative, "deleted"))
        elif before.read_bytes() != after.read_bytes():
            changes.append((relative, "modified"))
    return changes


def slug_for(relative: str) -> str:
    path = Path(relative)
    pieces = []
    if path.parent.name:
        pieces.append(path.parent.name)
    pieces.append(path.stem or path.name)
    slug = re.sub(r"[^A-Za-z0-9._-]+", "-", "-".join(pieces)).strip("-").lower()
    return slug or "patch"


def make_patch(
    pristine: Path,
    vendor: Path,
    relative: str,
    kind: str,
    work: Path,
) -> str:
    """Return a git-apply compatible patch with a/ and b/ crate-relative paths."""
    a_path = work / "a" / relative
    b_path = work / "b" / relative
    if kind in ("modified", "deleted"):
        a_path.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(pristine, a_path)
    if kind in ("modified", "added"):
        b_path.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(vendor, b_path)

    if kind == "added":
        command = [GIT, *GIT_CONFIG, "diff", "--no-index", "--no-prefix", "--", "/dev/null", f"b/{relative}"]
    elif kind == "deleted":
        command = [GIT, *GIT_CONFIG, "diff", "--no-index", "--no-prefix", "--", f"a/{relative}", "/dev/null"]
    else:
        command = [GIT, *GIT_CONFIG, "diff", "--no-index", "--no-prefix", "--", f"a/{relative}", f"b/{relative}"]

    result = run_raw(command, cwd=work)
    if result.returncode not in (0, 1):
        raise PatchQueueError(
            result.stderr.decode("utf-8", "replace").strip() or f"git diff failed for {relative}"
        )
    patch = result.stdout.decode("utf-8")
    if not patch.strip():
        raise PatchQueueError(f"empty diff for {relative}")

    if kind == "added":
        first, separator, rest = patch.partition("\n")
        if first.startswith("diff --git "):
            patch = f"diff --git a/{relative} b/{relative}{separator}{rest}"
    if kind == "deleted":
        first, separator, rest = patch.partition("\n")
        if first.startswith("diff --git "):
            patch = f"diff --git a/{relative} b/{relative}{separator}{rest}"
    if not patch.endswith("\n"):
        patch += "\n"
    return patch


def write_patch_set(
    sources: dict[str, Path],
    vendor_dirs: dict[str, Path],
    patch_dir: Path,
    manifest: dict,
) -> tuple[int, int]:
    if patch_dir.exists():
        if not (patch_dir / "series.tsv").is_file():
            raise PatchQueueError(
                f"refusing to replace {patch_dir}: it exists but has no series.tsv; "
                "move it aside or choose another --patch-dir"
            )
        shutil.rmtree(patch_dir)
    patch_dir.mkdir(parents=True)
    series: list[tuple[str, str, str, str]] = []
    total_files = 0

    for crate in manifest["crates"]:
        name = crate["name"]
        source = sources[name]
        vendor = vendor_dirs[name]
        changes = changed_files(source, vendor)
        if not changes:
            log(f"{name}: no local changes")
            continue
        crate_patch_dir = patch_dir / name
        crate_patch_dir.mkdir(parents=True)
        with tempfile.TemporaryDirectory(prefix=f"slint-patch-{name}-") as temp:
            work = Path(temp)
            for index, (relative, kind) in enumerate(changes, start=1):
                patch = make_patch(
                    pristine=source / relative,
                    vendor=vendor / relative,
                    relative=relative,
                    kind=kind,
                    work=work,
                )
                filename = f"{index:04d}-{slug_for(relative)}.patch"
                patch_path = crate_patch_dir / filename
                patch_path.write_bytes(patch.encode("utf-8"))
                series.append((name, patch_path.relative_to(patch_dir).as_posix(), relative, kind))
                total_files += 1
        log(f"{name}: {len(changes)} patch file(s)")

    with (patch_dir / "series.tsv").open("w", encoding="utf-8", newline="\n") as handle:
        handle.write("# crate\tpatch\tpath\tchange\n")
        for crate, patch, relative, kind in series:
            handle.write(f"{crate}\t{patch}\t{relative}\t{kind}\n")
    log(f"wrote {total_files} patch file(s) to {patch_dir}")
    return total_files, len(manifest["crates"])


def read_series(patch_dir: Path) -> list[tuple[str, Path, str]]:
    series_path = patch_dir / "series.tsv"
    if not series_path.is_file():
        raise PatchQueueError(f"series.tsv not found: {series_path}")
    rows: list[tuple[str, Path, str]] = []
    for line_number, line in enumerate(series_path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) < 3:
            raise PatchQueueError(f"invalid series line {line_number}: {line}")
        crate, relative_patch, relative_path = fields[:3]
        patch_path = patch_dir / relative_patch
        if not patch_path.is_file():
            raise PatchQueueError(f"patch listed in series is missing: {patch_path}")
        rows.append((crate, patch_path, relative_path))
    if not rows:
        raise PatchQueueError(f"series is empty: {series_path}")
    return rows


def series_by_crate(rows: list[tuple[str, Path, str]]) -> dict[str, list[tuple[Path, str]]]:
    grouped: dict[str, list[tuple[Path, str]]] = {}
    for crate, patch, relative in rows:
        grouped.setdefault(crate, []).append((patch, relative))
    return grouped


def copy_crate(source: Path, destination: Path) -> None:
    if destination.exists():
        shutil.rmtree(destination)
        log(f"removed existing {destination}")
    shutil.copytree(source, destination)


def apply_patch_rows(
    crate_name: str,
    patches: list[tuple[Path, str]],
    cwd: Path,
) -> list[tuple[str, str]]:
    rejected: list[tuple[str, str]] = []
    for patch_path, relative in patches:
        result = run([GIT, *GIT_CONFIG, "apply", "--reject", "--whitespace=nowarn", str(patch_path)], cwd=cwd)
        output = (result.stderr or "") + (result.stdout or "")
        skipped = "Skipped patch" in output
        if result.returncode != 0 or skipped:
            message = output.strip().splitlines()
            detail = message[-1] if message else "unknown apply error"
            log(f"REJECT {crate_name}/{relative}: {detail}")
            rejected.append((crate_name, relative))
        else:
            log(f"apply {crate_name}/{relative}")
    return rejected


def apply_series(
    source_by_crate: dict[str, Path],
    manifest: dict,
    patch_dir: Path,
    output_root: Path,
) -> list[tuple[str, str]]:
    rows = read_series(patch_dir)
    grouped = series_by_crate(rows)
    source_names = {crate["name"] for crate in manifest["crates"]}
    missing = set(grouped) - source_names
    if missing:
        raise PatchQueueError(f"series references crates absent from manifest: {sorted(missing)}")

    output_root.mkdir(parents=True, exist_ok=True)
    rejected: list[tuple[str, str]] = []
    # Apply in a temporary directory outside the rcho Git worktree.  `git apply`
    # silently skips files under an ignored path such as `target/`, so applying
    # directly to the output tree would report success while changing nothing.
    with tempfile.TemporaryDirectory(prefix="slint-apply-") as temp:
        staging = Path(temp)
        vendor_by_crate: dict[str, Path] = {}
        for crate in manifest["crates"]:
            name = crate["name"]
            if name not in source_by_crate:
                raise PatchQueueError(f"source missing for {name}")
            destination = staging / crate["vendor"]
            copy_crate(source_by_crate[name], destination)
            vendor_by_crate[name] = destination

        for crate in manifest["crates"]:
            name = crate["name"]
            patches = grouped.get(name, [])
            if not patches:
                continue
            rejected.extend(apply_patch_rows(name, patches, vendor_by_crate[name]))

        for crate in manifest["crates"]:
            name = crate["name"]
            copy_crate(vendor_by_crate[name], output_root / crate["vendor"])

        reject_files: list[str] = []
        for path in staging.rglob("*.rej"):
            relative = path.relative_to(staging)
            destination = output_root / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, destination)
            reject_files.append(str(relative))

    log(f"applied {len(rows) - len(rejected)}/{len(rows)} patch(es)")
    if rejected:
        log("conflicts need manual resolution; .rej files are under the output tree")
        for path in reject_files:
            log(f"  {path}")
    return rejected


def compare_trees(expected: Path, actual: Path) -> list[str]:
    expected_files = relative_files(expected)
    actual_files = relative_files(actual)
    problems: list[str] = []
    for relative in sorted(set(expected_files) | set(actual_files)):
        if ignored(relative):
            continue
        before = expected_files.get(relative)
        after = actual_files.get(relative)
        if before is None:
            problems.append(f"extra: {relative}")
        elif after is None:
            problems.append(f"missing: {relative}")
        elif before.read_bytes() != after.read_bytes():
            problems.append(f"different: {relative}")
    return problems


def verify_series(
    source_by_crate: dict[str, Path],
    vendor_dirs: dict[str, Path],
    manifest: dict,
    patch_dir: Path,
) -> list[str]:
    problems: list[str] = []
    rows = read_series(patch_dir)
    grouped = series_by_crate(rows)
    with tempfile.TemporaryDirectory(prefix="slint-verify-") as temp:
        staging = Path(temp)
        for crate in manifest["crates"]:
            name = crate["name"]
            source = source_by_crate[name]
            vendor = vendor_dirs[name]
            staged = staging / crate["vendor"]
            copy_crate(source, staged)
            rejected = apply_patch_rows(name, grouped.get(name, []), staged)
            if rejected:
                problems.append(f"{name}: patch queue rejected")
                continue
            tree_problems = compare_trees(vendor, staged)
            if tree_problems:
                problems.extend(f"{name}/{problem}" for problem in tree_problems)
    return problems


def vendor_dirs_from_manifest(manifest: dict, vendor_root: Path) -> dict[str, Path]:
    result: dict[str, Path] = {}
    for crate in manifest["crates"]:
        path = vendor_root / crate["vendor"]
        if not path.is_dir():
            raise PatchQueueError(f"vendor directory missing: {path}")
        result[crate["name"]] = path
    return result


def cmd_export(args: argparse.Namespace) -> int:
    manifest = load_manifest(Path(args.manifest).resolve())
    patch_dir = patch_dir_from(manifest, args.patch_dir)
    vendor_root = Path(args.vendor_root).resolve()
    vendor_dirs = vendor_dirs_from_manifest(manifest, vendor_root)
    if args.upstream_root:
        sources = sources_from_root(Path(args.upstream_root).resolve(), manifest)
    else:
        sources = download_sources(manifest)
    write_patch_set(sources, vendor_dirs, patch_dir, manifest)
    return 0


def cmd_verify(args: argparse.Namespace) -> int:
    manifest = load_manifest(Path(args.manifest).resolve())
    patch_dir = patch_dir_from(manifest, args.patch_dir)
    vendor_root = Path(args.vendor_root).resolve()
    vendor_dirs = vendor_dirs_from_manifest(manifest, vendor_root)
    if args.upstream_root:
        sources = sources_from_root(Path(args.upstream_root).resolve(), manifest)
    else:
        sources = download_sources(manifest)
    problems = verify_series(sources, vendor_dirs, manifest, patch_dir)
    if problems:
        log(f"verify failed with {len(problems)} difference(s):")
        for problem in problems[:40]:
            log(f"  {problem}")
        if len(problems) > 40:
            log(f"  ... {len(problems) - 40} more")
        return 1
    log("verify passed: patch queue reproduces the vendor tree")
    return 0


def cmd_apply(args: argparse.Namespace) -> int:
    manifest = load_manifest(Path(args.manifest).resolve())
    patch_dir = patch_dir_from(manifest, args.patch_dir)
    sources = sources_from_root(Path(args.upstream_root).resolve(), manifest)
    rejected = apply_series(sources, manifest, patch_dir, Path(args.out).resolve())
    if rejected:
        log(f"{len(rejected)} patch(es) rejected; resolve .rej files before capture")
        return 2
    log("all patches applied cleanly")
    return 0


def cmd_capture(args: argparse.Namespace) -> int:
    manifest = load_manifest(Path(args.manifest).resolve())
    patch_dir = Path(args.patch_dir).resolve()
    sources = sources_from_root(Path(args.upstream_root).resolve(), manifest)
    vendor_dirs = vendor_dirs_from_manifest(manifest, Path(args.vendor).resolve())
    write_patch_set(sources, vendor_dirs, patch_dir, manifest)
    log("update upstreams.json (versions and sha256) and Cargo.toml paths before building")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", default=str(DEFAULT_MANIFEST), help="path to upstreams.json")

    sub = parser.add_subparsers(dest="command", required=True)

    export = sub.add_parser("export", help="regenerate the patch queue from the current vendor tree")
    export.add_argument("--vendor-root", default=str(VENDOR_ROOT))
    export.add_argument("--upstream-root", help="directory containing pristine crate sources")
    export.add_argument("--patch-dir", help="override the patch directory from the manifest")
    export.set_defaults(func=cmd_export)

    verify = sub.add_parser("verify", help="apply the queue to pristine sources and compare with vendor")
    verify.add_argument("--vendor-root", default=str(VENDOR_ROOT))
    verify.add_argument("--upstream-root", help="directory containing pristine crate sources")
    verify.add_argument("--patch-dir", help="override the patch directory from the manifest")
    verify.set_defaults(func=cmd_verify)

    apply = sub.add_parser("apply", help="replay the queue onto a new upstream source tree")
    apply.add_argument("--upstream-root", required=True, help="directory containing new pristine crates")
    apply.add_argument("--out", required=True, help="staging directory for the patched vendor tree")
    apply.add_argument("--patch-dir", help="override the patch directory from the manifest")
    apply.set_defaults(func=cmd_apply)

    capture = sub.add_parser("capture", help="write a new patch queue after resolving conflicts")
    capture.add_argument("--upstream-root", required=True, help="directory containing new pristine crates")
    capture.add_argument("--vendor", required=True, help="patched vendor tree with manifest vendor names")
    capture.add_argument("--patch-dir", required=True, help="new patch directory to write")
    capture.set_defaults(func=cmd_capture)

    return parser


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()
    try:
        return args.func(args)
    except PatchQueueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        return 130


if __name__ == "__main__":
    raise SystemExit(main())
