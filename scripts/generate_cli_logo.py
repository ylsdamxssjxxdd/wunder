#!/usr/bin/env python3
"""Convert the transparent EVA head image into compact, terminal-ready Rust data."""

from __future__ import annotations

from pathlib import Path

import numpy as np
from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "images" / "eva01-head.png"
OUTPUT = ROOT / "crates" / "wunder-cli" / "welcome_logo_art.rs"
WIDTH = 40
PIXEL_HEIGHT = 34
PALETTE_SIZE = 15  # Palette slot 15 encodes transparent pixels.


def main() -> None:
    image = Image.open(SOURCE).convert("RGBA")
    alpha = image.getchannel("A")
    image = image.crop(alpha.getbbox())
    image.thumbnail((WIDTH, PIXEL_HEIGHT), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (WIDTH, PIXEL_HEIGHT), (0, 0, 0, 0))
    canvas.alpha_composite(image, ((WIDTH - image.width) // 2, (PIXEL_HEIGHT - image.height) // 2))

    rgb = canvas.convert("RGB")
    quantized = rgb.quantize(colors=PALETTE_SIZE, method=Image.Quantize.MEDIANCUT)
    palette_raw = quantized.getpalette()[: PALETTE_SIZE * 3]
    palette = [tuple(palette_raw[index:index + 3]) for index in range(0, len(palette_raw), 3)]

    pixels = np.asarray(rgb, dtype=np.int16)
    alpha_values = np.asarray(canvas.getchannel("A"), dtype=np.uint8)
    palette_array = np.asarray(palette, dtype=np.int16)
    distances = ((pixels[:, :, None, :] - palette_array[None, None, :, :]) ** 2).sum(axis=3)
    indices = distances.argmin(axis=2).astype(np.uint8)
    indices[alpha_values < 80] = 15

    rows = []
    for y in range(0, PIXEL_HEIGHT, 2):
        encoded = "".join(f"{(int(indices[y, x]) << 4) | int(indices[y + 1, x]):02x}" for x in range(WIDTH))
        rows.append(encoded)

    lines = [
        "// Generated by scripts/generate_cli_logo.py; do not edit by hand.",
        f"pub(super) const SOURCE_WIDTH: usize = {WIDTH};",
        f"pub(super) const SOURCE_HEIGHT: usize = {PIXEL_HEIGHT};",
        "pub(super) const PALETTE: [[u8; 3]; 15] = [",
    ]
    lines.extend(f"    [{r}, {g}, {b}]," for r, g, b in palette)
    lines.extend(["];"])
    lines.append(f"pub(super) const ROWS: [&str; {len(rows)}] = [")
    lines.extend(f'    "{row}",' for row in rows)
    lines.extend(["];"])
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({WIDTH} x {PIXEL_HEIGHT} pixels)")


if __name__ == "__main__":
    main()
