#!/usr/bin/env python3
"""Convert the transparent EVA head image into compact, terminal-ready Rust data.

The output is deliberately colourless: every palette slot is a neutral grey, so the
banner reads as white/grey relief and never fights the accent colours of the UI.
Slot 15 encodes transparent pixels; the other 15 slots form a grey ladder that keeps
the volume of the head (white specular, deep grey shadows).
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "images" / "eva01-head.png"
OUTPUT = ROOT / "crates" / "wunder-cli" / "welcome_logo_art.rs"
WIDTH = 40
PIXEL_HEIGHT = 34
PALETTE_SIZE = 15  # Palette slot 15 encodes transparent pixels.
ALPHA_CUTOFF = 80
GREY_FLOOR = 48  # Deepest shadow still readable on a dark terminal.
GREY_CEIL = 255  # Specular highlight is pure white.
CONTRAST = 1.18  # Mild S-curve so the relief does not flatten out.


def grey_ladder() -> list[int]:
    span = GREY_CEIL - GREY_FLOOR
    return [round(GREY_FLOOR + index * span / (PALETTE_SIZE - 1)) for index in range(PALETTE_SIZE)]


def luminance(canvas: Image.Image) -> np.ndarray:
    pixels = np.asarray(canvas.convert("RGB"), dtype=np.float64)
    return pixels[:, :, 0] * 0.2126 + pixels[:, :, 1] * 0.7152 + pixels[:, :, 2] * 0.0722


def stretch(values: np.ndarray, opaque: np.ndarray) -> np.ndarray:
    low, high = np.percentile(values[opaque], (2.0, 98.0))
    scale = max(high - low, 1.0)
    normalised = np.clip((values - low) / scale, 0.0, 1.0)
    curved = np.clip(0.5 + (normalised - 0.5) * CONTRAST, 0.0, 1.0)
    return GREY_FLOOR + curved * (GREY_CEIL - GREY_FLOOR)


def main() -> None:
    image = Image.open(SOURCE).convert("RGBA")
    alpha = image.getchannel("A")
    image = image.crop(alpha.getbbox())
    image.thumbnail((WIDTH, PIXEL_HEIGHT), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (WIDTH, PIXEL_HEIGHT), (0, 0, 0, 0))
    canvas.alpha_composite(image, ((WIDTH - image.width) // 2, (PIXEL_HEIGHT - image.height) // 2))

    alpha_values = np.asarray(canvas.getchannel("A"), dtype=np.uint8)
    opaque = alpha_values >= ALPHA_CUTOFF
    grey = stretch(luminance(canvas), opaque)

    ladder = np.asarray(grey_ladder(), dtype=np.float64)
    indices = np.abs(grey[:, :, None] - ladder[None, None, :]).argmin(axis=2).astype(np.uint8)
    indices[~opaque] = PALETTE_SIZE  # Slot 15 / transparent.

    rows = []
    for y in range(0, PIXEL_HEIGHT, 2):
        encoded = "".join(
            f"{(int(indices[y, x]) << 4) | int(indices[y + 1, x]):02x}" for x in range(WIDTH)
        )
        rows.append(encoded)

    palette = grey_ladder()
    lines = [
        "// Generated by scripts/generate_cli_logo.py; do not edit by hand.",
        "// Colourless by design: the palette is a neutral grey ladder, slot 15 = transparent.",
        f"pub(super) const SOURCE_WIDTH: usize = {WIDTH};",
        f"pub(super) const SOURCE_HEIGHT: usize = {PIXEL_HEIGHT};",
        "pub(super) const PALETTE: [[u8; 3]; 15] = [",
    ]
    lines.extend(f"    [{value}, {value}, {value}]," for value in palette)
    lines.extend(["];"])
    lines.append(f"pub(super) const ROWS: [&str; {len(rows)}] = [")
    lines.extend(f'    "{row}",' for row in rows)
    lines.extend(["];"])
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(
        f"wrote {OUTPUT.relative_to(ROOT)} ({WIDTH} x {PIXEL_HEIGHT} pixels, "
        f"grey {GREY_FLOOR}-{GREY_CEIL})"
    )


if __name__ == "__main__":
    main()